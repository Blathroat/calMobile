import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const sourceDir = resolve(root, 'status-page');
const target = resolve(root, 'src/status-page-assets.ts');

const [template, fallback, styles, client] = await Promise.all([
  readFile(resolve(sourceDir, 'template.html'), 'utf8'),
  readFile(resolve(sourceDir, 'fallback.html'), 'utf8'),
  readFile(resolve(sourceDir, 'styles.css'), 'utf8'),
  readFile(resolve(sourceDir, 'client.ts'), 'utf8'),
]);

for (const [name, content, marker] of [
  ['template', template, '__STYLES__'],
  ['fallback', fallback, '__STYLES__'],
  ['template', template, '__COUNT_FIELDS__'],
  ['template', template, '__CLIENT_SCRIPT__'],
  ['client', client, '__INITIAL__'],
]) {
  if (!content.includes(marker)) {
    throw new Error(`${name} 缺少构建占位符 ${marker}`);
  }
}

const literal = (value) => JSON.stringify(value);
const generated =
  `/** Generated by scripts/build-status-page.ts. Edit server/status-page/* instead. */\n\n` +
  `export const STATUS_PAGE_TEMPLATE = ${literal(template)};\n` +
  `export const STATUS_PAGE_FALLBACK = ${literal(fallback)};\n` +
  `export const STATUS_PAGE_STYLES = ${literal(styles)};\n` +
  `export const STATUS_PAGE_CLIENT_SCRIPT = ${literal(client)};\n`;

let previous = '';
try {
  previous = await readFile(target, 'utf8');
} catch (error) {
  if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
}
if (previous !== generated) await writeFile(target, generated, 'utf8');
